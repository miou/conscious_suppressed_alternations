function finish_standard_figure(fig, ax, S, varargin)
%FINISH_STANDARD_FIGURE_WIDTH_UNITS_V2 Finalize and optionally export a standard figure.
%
%   finish_standard_figure_width_units_v2(fig, ax, S)
%
% OPTIONAL NAME-VALUE ARGUMENTS
%
%   'OutputBase'
%       Output filename without extension.
%       Default: 'figure'
%
%   'SaveFIG'
%       Save MATLAB .fig file.
%       Default: false
%
%   'ExportPDF'
%       Export transparent vector PDF.
%       Default: false
%
%   'ExportSVG'
%       Export transparent vector SVG.
%       Default: false
%
%   'ExportPNG'
%       Export transparent PNG.
%       Default: false
%
%   'ExportEMF'
%       Export EMF for PowerPoint on Windows.
%       Default: false
%
%   'CloseAfterExport'
%       Close figure after exporting.
%       Default: false
%
%   'PNGResolution'
%       PNG resolution in dpi.
%       Default: S.png_resolution when available.
%
% NOTES
%
% The live MATLAB preview remains white so the figure stays visible in
% MATLAB dark mode.
%
% Transparency is applied only to exported PDF, SVG, and PNG files through
% exportgraphics(..., 'BackgroundColor', 'none').

%% Parse inputs

p = inputParser;

addRequired(p, 'fig', @(x) isgraphics(x, 'figure'));

addRequired( ...
    p, ...
    'ax', ...
    @(x) all(isgraphics(x, 'axes')));

addRequired(p, 'S', @isstruct);

addParameter( ...
    p, ...
    'OutputBase', ...
    'figure', ...
    @(x) ischar(x) || isstring(x));

addParameter( ...
    p, ...
    'SaveFIG', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

addParameter( ...
    p, ...
    'ExportPDF', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

addParameter( ...
    p, ...
    'ExportSVG', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

addParameter( ...
    p, ...
    'ExportPNG', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

addParameter( ...
    p, ...
    'ExportEMF', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

addParameter( ...
    p, ...
    'CloseAfterExport', ...
    false, ...
    @(x) islogical(x) && isscalar(x));

default_png_resolution = 300;

if isfield(S, 'png_resolution')
    default_png_resolution = S.png_resolution;
end

addParameter( ...
    p, ...
    'PNGResolution', ...
    default_png_resolution, ...
    @(x) isnumeric(x) && isscalar(x) && x > 0);

parse(p, fig, ax, S, varargin{:});

output_base = char(p.Results.OutputBase);

%% Keep the live MATLAB preview white

set(fig, ...
    'Color', [1 1 1], ...
    'Renderer', 'painters', ...
    'InvertHardcopy', 'off');

%% Standardize axes

for axes_index = 1:numel(ax)

    current_axes = ax(axes_index);

    set(current_axes, ...
        'Color', 'none', ...
        'Box', 'off', ...
        'TickDir', S.tick_direction, ...
        'Layer', 'top', ...
        'FontName', S.font_name, ...
        'FontSize', S.font_size, ...
        'FontWeight', 'normal', ...
        'LineWidth', S.axes_line_width, ...
        'XColor', S.axis_color, ...
        'YColor', S.axis_color);

    if isprop(current_axes, 'TickLength') && isfield(S, 'tick_length')
        current_axes.TickLength = S.tick_length;
    end

    if isprop(current_axes, 'GridAlpha') && isfield(S, 'grid_alpha')
        current_axes.GridAlpha = S.grid_alpha;
    end

    if isprop(current_axes, 'MinorGridAlpha') && ...
            isfield(S, 'minor_grid_alpha')

        current_axes.MinorGridAlpha = S.minor_grid_alpha;
    end

    set(current_axes.XLabel, ...
        'FontName', S.font_name, ...
        'FontSize', S.label_font_size, ...
        'FontWeight', 'normal', ...
        'Color', S.text_color, ...
        'Interpreter', S.interpreter);

    set(current_axes.YLabel, ...
        'FontName', S.font_name, ...
        'FontSize', S.label_font_size, ...
        'FontWeight', 'normal', ...
        'Color', S.text_color, ...
        'Interpreter', S.interpreter);

    set(current_axes.ZLabel, ...
        'FontName', S.font_name, ...
        'FontSize', S.label_font_size, ...
        'FontWeight', 'normal', ...
        'Color', S.text_color, ...
        'Interpreter', S.interpreter);

    set(current_axes.Title, ...
        'FontName', S.font_name, ...
        'FontSize', S.title_font_size, ...
        'FontWeight', 'bold', ...
        'Color', S.text_color, ...
        'Interpreter', S.interpreter);
end

%% Standardize legends

legend_objects = findall(fig, 'Type', 'legend');

for legend_index = 1:numel(legend_objects)

    current_legend = legend_objects(legend_index);

    set(current_legend, ...
        'FontName', S.font_name, ...
        'FontSize', S.font_size, ...
        'FontWeight', 'normal', ...
        'Box', 'off', ...
        'Color', 'none', ...
        'TextColor', S.text_color, ...
        'Interpreter', S.interpreter);

    if isprop(current_legend, 'ItemTokenSize') && ...
            isfield(S, 'legend_token_size')

        current_legend.ItemTokenSize = ...
            [S.legend_token_size S.legend_token_size];
    end
end

%% Standardize annotation text

text_objects = findall(fig, 'Type', 'text');

for text_index = 1:numel(text_objects)

    current_text = text_objects(text_index);

    set(current_text, ...
        'FontName', S.font_name, ...
        'Color', S.text_color);

    if isprop(current_text, 'Interpreter')
        current_text.Interpreter = S.interpreter;
    end
end

annotation_textboxes = findall(fig, 'Type', 'textboxshape');

for annotation_index = 1:numel(annotation_textboxes)

    current_annotation = annotation_textboxes(annotation_index);

    set(current_annotation, ...
        'FontName', S.font_name, ...
        'Color', S.text_color, ...
        'BackgroundColor', 'none', ...
        'EdgeColor', 'none');
end

%% Restore exact axes positions

drawnow;

if isfield(S, 'axes_position')

    if numel(ax) == 1

        set(ax, ...
            'Units', 'inches', ...
            'PositionConstraint', 'innerposition', ...
            'Position', S.axes_position);

    elseif size(S.axes_position, 1) == numel(ax)

        for axes_index = 1:numel(ax)

            set(ax(axes_index), ...
                'Units', 'inches', ...
                'PositionConstraint', 'innerposition', ...
                'Position', S.axes_position(axes_index, :));
        end
    end
end

drawnow;

%% Configure physical output dimensions

if isfield(S, 'figure_width') && isfield(S, 'figure_height')

    set(fig, ...
        'PaperUnits', 'inches', ...
        'PaperPositionMode', 'manual', ...
        'PaperPosition', [ ...
            0, ...
            0, ...
            S.figure_width, ...
            S.figure_height], ...
        'PaperSize', [ ...
            S.figure_width, ...
            S.figure_height]);
end

%% Determine whether export is requested

do_export = ...
    p.Results.SaveFIG || ...
    p.Results.ExportPDF || ...
    p.Results.ExportSVG || ...
    p.Results.ExportPNG || ...
    p.Results.ExportEMF;

if ~do_export
    return
end

%% Create output folder when needed

[output_folder, ~, ~] = fileparts(output_base);

if ~isempty(output_folder) && ~exist(output_folder, 'dir')
    mkdir(output_folder);
end

%% Save MATLAB figure

if p.Results.SaveFIG

    savefig(fig, [output_base '.fig']);
end

%% Export transparent PDF

if p.Results.ExportPDF

    exportgraphics( ...
        fig, ...
        [output_base '.pdf'], ...
        'ContentType', 'vector', ...
        'BackgroundColor', 'none');
end

%% Export transparent SVG

if p.Results.ExportSVG

    % exportgraphics( ...
    %     fig, ...
    %     [output_base '.svg'], ...
    %     'ContentType', 'vector', ...
    %     'BackgroundColor', 'none');
% Export SVG
old_renderer = fig.Renderer;
old_color = fig.Color;



set(fig, ...
    'Renderer', 'painters', ...
    'Color', 'none');

print( ...
    fig, ...
    [output_base '.svg'], ...
    '-dsvg', ...
    '-painters');

set(fig, ...
    'Renderer', old_renderer, ...
    'Color', old_color);
end

%% Export transparent PNG

if p.Results.ExportPNG

    exportgraphics( ...
        fig, ...
        [output_base '.png'], ...
        'Resolution', p.Results.PNGResolution, ...
        'BackgroundColor', 'none');
end

%% Export EMF

if p.Results.ExportEMF

    old_renderer = fig.Renderer;
    old_color = fig.Color;
    set(fig, ...
    'Renderer', 'painters', ...
    'Color', 'none');

    print( ...
        fig, ...
        [output_base '.emf'], ...
        '-dmeta');

    set(fig, ...
        'Renderer', old_renderer, ...
        'Color', old_color);
end

%% Restore white live preview after export

set(fig, 'Color', [1 1 1]);

drawnow;

%% Optionally close figure

if p.Results.CloseAfterExport
    close(fig);
end

end